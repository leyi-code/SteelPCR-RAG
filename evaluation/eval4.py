def _append_jsonl(path: Path, obj: Dict[str, Any]) -> None:
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(obj, ensure_ascii=False) + "\n")
        f.flush()


def _load_jsonl_last_wins(path: Path, key: str = "qid") -> Dict[str, Any]:
    """Read a slice; when one qid has several rows the last one wins (same semantics as eval3's candidate pool)."""
    out: Dict[str, Any] = {}
    if not path.exists():
        return out
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except Exception:
                continue
            k = d.get(key)
            if k:
                out[k] = d
    return out


