ONE_CLICK_BANNER = """
================================================================
 [one-click mode] no subcommand given -> runs: run --arms all
   full run = 4 ablation arms x 355 items, strictly serial, roughly 40-50 hours
   Ctrl+C any time; the checkpoint is kept and the next one-click run resumes automatically
   helper commands: python eval4.py status | repair | report | prepare
================================================================
"""

def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Experiment 4: component ablation")
    sub = parser.add_subparsers(dest="cmd")

    p_prep = sub.add_parser("prepare", help="zero-API self check and arm list")
    p_prep.add_argument("--cache-dir", default=EVAL4_CACHE_DIR)

    p_run = sub.add_parser("run", help="run the ablation arms (serial, resumable)")
    p_run.add_argument("--arms", nargs="+", default=["all"], help="arm names, or all")
    p_run.add_argument("--cache-dir", default=EVAL4_CACHE_DIR)
    p_run.add_argument("--output-dir", default=EVAL4_OUTPUT_DIR)
    p_run.add_argument("--limit", type=int, default=None, help="run only the first N items")
    p_run.add_argument("--stratified", type=int, default=None, help="sample N items stratified by question type (smoke/pilot)")
    p_run.add_argument("--qids-file", default=None, help="file listing qids, one per line")
    p_run.add_argument("--dry-run", action="store_true", help="route preview only, no API call")
    p_run.add_argument("--force", action="store_true", help="ignore the checkpoint and re-run")
    p_run.add_argument("--max-fail-streak", type=int, default=5, help="circuit breaker: consecutive failures before stopping")
    p_run.add_argument("--ragas-retry", type=int, default=RAGAS_RETRY, help="whole-block RAGAS retries when a metric is missing")
    p_run.add_argument("--ragas-backoff", type=float, default=RAGAS_BACKOFF, help="RAGAS backoff base in seconds (exponential)")
    p_run.add_argument("--pace-sec", type=float, default=PACE_SEC, help="mandatory pause between items, in seconds")

    p_rep = sub.add_parser("repair", help="single-metric NaN repair")
    p_rep.add_argument("--cache-dir", default=EVAL4_CACHE_DIR)

    p_st = sub.add_parser("status", help="checkpoint inspection")
    p_st.add_argument("--cache-dir", default=EVAL4_CACHE_DIR)

    p_cp = sub.add_parser("compact", help="compact slices by removing duplicate rows")
    p_cp.add_argument("--cache-dir", default=EVAL4_CACHE_DIR)

    p_rp = sub.add_parser("report", help="report tables and statistics (no API)")
    p_rp.add_argument("--arms", nargs="+", default=["all"])
    p_rp.add_argument("--cache-dir", default=EVAL4_CACHE_DIR)
    p_rp.add_argument("--output-dir", default=EVAL4_OUTPUT_DIR)

    args = parser.parse_args(argv)

    if args.cmd is None:
        # One-click mode: pressing Run in VSCode with no arguments runs all four arms serially
        print(ONE_CLICK_BANNER, flush=True)
        args = parser.parse_args(["run", "--arms", "all"])

    if args.cmd == "prepare":
        run_prepare(args.cache_dir)
    elif args.cmd == "run":
        arms = DEFAULT_ARMS if "all" in args.arms else [a for a in args.arms if a in ARM_DEFS]
        unknown = [a for a in args.arms if a != "all" and a not in ARM_DEFS]
        if unknown:
            raise SystemExit(f"Unknown arm name: {unknown}; choose from {DEFAULT_ARMS} or all")
        run_arms(
            arms=arms, cache_dir=args.cache_dir, output_dir=args.output_dir,
            limit=args.limit, stratified=args.stratified, qids_file=args.qids_file,
            dry_run=args.dry_run, force=args.force, max_fail_streak=args.max_fail_streak,
            ragas_retry=args.ragas_retry, ragas_backoff=args.ragas_backoff, pace_sec=args.pace_sec,
        )
    elif args.cmd == "repair":
        repair_nan_checkpoint_records(args.cache_dir)
    elif args.cmd == "status":
        run_status(args.cache_dir)
    elif args.cmd == "compact":
        run_compact(args.cache_dir)
    elif args.cmd == "report":
        arms = DEFAULT_ARMS if "all" in args.arms else args.arms
        run_report(arms=arms, cache_dir=args.cache_dir, output_dir=args.output_dir)


if __name__ == "__main__":
    main()
