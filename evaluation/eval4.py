def resolve_query(qid: str, question: str, use_bilingual: bool) -> Tuple[str, str]:
    """
    Return (query used for retrieval, mode label).

    Bilingual mode (on in every arm except A2) reproduces production behaviour exactly:
      1) prefer the static production artefact `rag_core/query_expansion_355.json` (read-only, O(1));
      2) when a qid is missing, call the LLM, and append the result to a make-up file inside the
         WORKING tree (`cache4/query_expansion_missing.json`) - production files are never written;
      3) when the LLM is unavailable, fall back to the raw Chinese question and tag the row
    """
    if not use_bilingual:
        return question.strip(), "raw_question"
    cache = _load_expansion_cache()
    hit = cache.get(qid)
    if hit and str(hit).strip():
        return str(hit).strip(), "bilingual_expanded"
    expanded = expand_query_with_llm(question)
    if expanded and expanded.strip() and expanded.strip() != question.strip():
        _append_expansion_missing(qid, expanded.strip())
        return expanded.strip(), "bilingual_llm_generated"
    return question.strip(), "bilingual_miss_fallback_raw"


_EXPANSION_CACHE_MEMO: Optional[Dict[str, str]] = None


def _expansion_cache_paths() -> List[Path]:
    return [
        E_ROOT / "rag_core" / "query_expansion_355.json",   # production artefact (read-only)
        WORK_ROOT / "rag_core" / "query_expansion_355.json",  # mirror inside this tree (read-only fallback)
    ]


def _load_expansion_cache() -> Dict[str, str]:
    global _EXPANSION_CACHE_MEMO
    if _EXPANSION_CACHE_MEMO is not None:
        return _EXPANSION_CACHE_MEMO
    data: Dict[str, str] = {}
    for p in _expansion_cache_paths():
        if p.exists():
            try:
                with open(p, "r", encoding="utf-8") as f:
                    data = json.load(f)
                print(f"   Bilingual expansion: loaded the static artefact {p} ({len(data)} entries)")
                break
            except Exception as exc:
                print(f"   [WARN] Failed to read the bilingual artefact {p}: {exc}")
    missing_path = Path(EVAL4_CACHE_DIR) / "query_expansion_missing.json"
    if missing_path.exists():
        try:
            with open(missing_path, "r", encoding="utf-8") as f:
                data.update(json.load(f))
        except Exception:
            pass
    _EXPANSION_CACHE_MEMO = data
    return data


def _append_expansion_missing(qid: str, expanded: str) -> None:
    """Append a freshly generated expansion inside the working tree; production files are never touched."""
    global _EXPANSION_CACHE_MEMO
    path = Path(EVAL4_CACHE_DIR) / "query_expansion_missing.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    data: Dict[str, str] = {}
    if path.exists():
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            data = {}
    data[qid] = expanded
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    if _EXPANSION_CACHE_MEMO is not None:
        _EXPANSION_CACHE_MEMO[qid] = expanded


def retrieve_top50(retriever: DenseRetriever, query: str) -> List[Dict]:
    """
    Return the candidate pool, preserving DenseRetriever's own order exactly.
    Guard rail: _dense_score is a FAISS L2 distance (smaller is better) and retrieve() already
    returns the true ranking. Sorting by _dense_score descending would turn a Recall@7 of ~0.84 into ~0.54.
    """
    cands = retriever.retrieve(query, top_k=TOP_K_RETRIEVE)
    scores = []
    for c in cands:
        try:
            scores.append(float(c.get("_dense_score", 0.0)))
        except Exception:
            scores.append(0.0)
    if scores != sorted(scores):
        raise AssertionError(
            "Candidate-pool order assertion failed: DenseRetriever must return L2 distances in ascending order (best first). "
            "If the retriever's scoring convention changed upstream, fix this function before running the ablation."
        )
    return cands


def build_evidence(
    arm_def: Dict[str, Any],
    question: str,
    candidates: List[Dict],
    reranker: Optional[Qwen3RerankerAPI],
) -> Tuple[List[Dict], float, bool, Optional[str]]:
    """Rerank (or take the top 7 in retrieval order) to obtain this arm's strict top-7 evidence."""
    if not candidates:
        return [], 0.0, False, "candidate pool is empty"

    if not arm_def["use_reranker"]:
        # A1: no reranking at all; take the first 7 in retrieval order (the no-rerank baseline)
        return list(candidates[:TOP_K_RERANK]), 0.0, True, None

    assert reranker is not None
    docs, lat, ok, err = reranker.rerank(query=question, candidates=candidates, top_k=TOP_K_RERANK)
    return docs, lat, ok, err


def build_generation_docs(arm_def: Dict[str, Any], strict_docs: List[Dict]) -> List[Dict]:
    """Context expansion and merging (when A3 is on, the strict top 7 are kept as they are)."""
    if not strict_docs:
        return []
    if not arm_def["use_ctx_enhance"]:
        return list(strict_docs)
    try:
        return enhance_context(retrieved_records=strict_docs, expand_window=1, fill_internal_gaps=True)
    except Exception as exc:
        print(f"      [WARN] Context enhancement failed; falling back to the raw evidence: {exc}")
        return list(strict_docs)


def ctx_enhance_diagnostics(strict_docs: List[Dict]) -> Dict[str, Any]:
    """Offline diagnosis, no API: what would happen to this item if context enhancement were on? Used to stratify A3."""
    n_before = len(strict_docs)
    try:
        enh = enhance_context(retrieved_records=strict_docs, expand_window=1, fill_internal_gaps=True)
    except Exception:
        enh = list(strict_docs)
    n_after = len(enh)
    merged_text = "\n\n".join(d.get("text", "") for d in enh)
    raw_text = "\n\n".join(d.get("text", "") for d in strict_docs)
    return {
        "n_strict": n_before,
        "n_after_enhance": n_after,
        "would_merge": 1 if n_after < n_before else 0,
        "would_merge_count": max(0, n_before - n_after),
        "para_tag_count": len(TAG_PARA_RE.findall(merged_text)),
        "table_title_count": len(TAG_TABLE_RE.findall(merged_text)),
        "table_fence_count": merged_text.count("```markdown"),
        "enhance_char_delta": len(merged_text) - len(raw_text),
        "has_table": 1 if any(d.get("block_type") == "table" for d in strict_docs) else 0,
        "has_formula": 1 if any(d.get("block_type") in ("formula", "equation") for d in strict_docs) else 0,
    }


def score_evidence(gold_paragraph: str, docs: List[Dict], candidates: List[Dict]) -> Dict[str, Any]:
    """Retrieval metrics: Recall/MRR/nDCG over the top 7, gold coverage of the candidate pool and the first gold rank."""
    k = TOP_K_RERANK
    if not (gold_paragraph or "").strip():
        return {f"Recall@{k}": None, f"MRR@{k}": None, f"nDCG@{k}": None,
                f"CandidateRecall@{TOP_K_RETRIEVE}": None,
                "CandidateFirstRank": None, "StrictFirstRank": None}
    m = compute_retrieval_metrics(gold_paragraph, docs, k=k) if docs else {
        f"Recall@{k}": 0.0, f"MRR@{k}": 0.0, f"nDCG@{k}": 0.0
    }
    first_cand_rank = 0
    for i, c in enumerate(candidates or [], start=1):
        hit, _ = is_evidence_match(gold_paragraph, c)
        if hit:
            first_cand_rank = i
            break
    m[f"CandidateRecall@{TOP_K_RETRIEVE}"] = 1.0 if first_cand_rank else 0.0
    m["CandidateFirstRank"] = first_cand_rank

    first_strict_rank = 0
    for i, d in enumerate(docs or [], start=1):
        hit, _ = is_evidence_match(gold_paragraph, d)
        if hit:
            first_strict_rank = i
            break
    m["StrictFirstRank"] = first_strict_rank
    return m


