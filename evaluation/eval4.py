def generate_with_context(
    question: str,
    context: str,
    model_name: str = GEN_MODEL,
    api_base: str = GEN_API_BASE,
    api_key: str = GEN_API_KEY,
    temperature: float = GEN_TEMPERATURE,
    max_tokens: Optional[int] = GEN_MAX_TOKENS,
    max_retries: int = GEN_MAX_RETRIES,
) -> Tuple[str, str]:
    """Generate through an OpenAI-compatible endpoint; returns (answer, finish_reason)."""
    from openai import OpenAI

    if not context:
        return "知识库中没有检索到可用于回答该问题的证据。", "no_context"

    client = OpenAI(api_key=api_key, base_url=api_base, timeout=GEN_TIMEOUT)
    last_err = None
    for attempt in range(max_retries + 1):
        try:
            request_kwargs = {
                "model": model_name,
                "messages": [
                    {"role": "system", "content": GEN_SYSTEM_PROMPT},
                    {"role": "user", "content": build_user_prompt(question, context)},
                ],
                "temperature": temperature,
                "timeout": GEN_TIMEOUT,
            }
            if max_tokens is not None:
                request_kwargs["max_tokens"] = max_tokens
            resp = client.chat.completions.create(**request_kwargs)
            choice = resp.choices[0]
            ans = (choice.message.content or "").strip()
            finish_reason = getattr(choice, "finish_reason", "stop") or "stop"
            if ans:
                return ans, finish_reason
            last_err = f"The API returned empty content (finish_reason={finish_reason})"
        except Exception as exc:
            last_err = exc
        if attempt < max_retries:
            time.sleep(2.0)
    return f"ERROR: generation failed ({last_err})", "error"


