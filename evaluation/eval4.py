def _finite(x: Any) -> Optional[float]:
    try:
        v = float(x)
    except Exception:
        return None
    return None if (math.isnan(v) or math.isinf(v)) else v


def mean_or_none(xs: List[Any]) -> Optional[float]:
    vals = [_finite(x) for x in xs]
    vals = [v for v in vals if v is not None]
    return (sum(vals) / len(vals)) if vals else None


def fmt(v: Optional[float], nd: int = 4) -> str:
    return "-" if v is None else f"{v:.{nd}f}"


def bootstrap_ci_paired(diffs: List[float], n_boot: int = 10000, seed: int = 42,
                        alpha: float = 0.05) -> Tuple[float, float]:
    """Bootstrap 95% percentile interval of the paired differences."""
    if not diffs:
        return (float("nan"), float("nan"))
    rng = random.Random(seed)
    n = len(diffs)
    stats_ = []
    for _ in range(n_boot):
        s = 0.0
        for _ in range(n):
            s += diffs[rng.randrange(n)]
        stats_.append(s / n)
    stats_.sort()
    lo = stats_[int(alpha / 2 * n_boot)]
    hi = stats_[int((1 - alpha / 2) * n_boot) - 1]
    return (lo, hi)


def mcnemar_exact_p(b: int, c: int) -> float:
    """Exact McNemar test (two-sided): b = baseline correct, arm wrong; c = baseline wrong, arm correct."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    tail = sum(math.comb(n, i) for i in range(0, k + 1)) / (2 ** n)
    return min(1.0, 2.0 * tail)


def wilcoxon_p(diffs: List[float]) -> Optional[float]:
    d = [x for x in diffs if x != 0]
    if not d:
        return 1.0
    try:
        from scipy.stats import wilcoxon
        return float(wilcoxon(d, zero_method="wilcox", alternative="two-sided").pvalue)
    except Exception:
        return None


def cliffs_delta(a: List[float], b: List[float]) -> Optional[float]:
    """Cliff's delta effect size (unpaired, range [-1, 1])."""
    if not a or not b:
        return None
    gt = lt = 0
    for x in a:
        for y in b:
            if x > y:
                gt += 1
            elif x < y:
                lt += 1
    return (gt - lt) / (len(a) * len(b))


def holm_adjust(pvals: Dict[str, float]) -> Dict[str, float]:
    items = sorted(((k, v) for k, v in pvals.items() if v is not None), key=lambda kv: kv[1])
    m = len(items)
    out: Dict[str, float] = {}
    running = 0.0
    for i, (k, p) in enumerate(items):
        adj = min(1.0, p * (m - i))
        running = max(running, adj)
        out[k] = running
    return out


def t1(x: Any) -> float:
    """Binarise: AC >= 0.75."""
    v = _finite(x)
    return 0.0 if v is None else (1.0 if v >= FC_THRESHOLD else 0.0)


def graded(x: Any) -> float:
    v = _finite(x)
    if v is None:
        return float("nan")
    return (2.0 if v >= FC_THRESHOLD else (1.0 if v >= GRADE_MID else 0.0)) / 2.0


def grounded_fc(rec: Dict[str, Any]) -> float:
    ac, fa = _finite(rec.get("AnswerCorrectness")), _finite(rec.get("Faithfulness"))
    if ac is None or fa is None:
        return float("nan")
    return 1.0 if (ac >= FC_THRESHOLD and fa >= GROUNDED_FAITH) else 0.0


