def load_baseline() -> Dict[str, Dict[str, Any]]:
    out: Dict[str, Dict[str, Any]] = {}
    p = Path(PROD_EVAL3_CKPT)
    if not p.exists():
        print(f"[WARN] baseline checkpoint not found: {p}")
        return out
    with open(p, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            d = json.loads(line)
            if d.get("system") != PROD_FULL_SYSTEM:
                continue
            # Derive the deterministic indicators with the same convention as the ablation arms
            num = numeric_accuracy(d.get("reference_answer", ""), d.get("generated_answer", "") or "")
            cit = citation_stats(d.get("generated_answer", "") or "", [])
            d = dict(d)
            d.update(num)
            d.update({k: cit[k] for k in ("cite_count", "unique_cite", "has_cite", "mentions_evidence_word")})
            d["system"] = BASELINE_NAME
            d["baseline_source"] = PROD_FULL_SYSTEM
            out[d.get("qid")] = d
    return out


def load_arm_records(cache_dir: str, arms: List[str]) -> Dict[str, Dict[str, Dict[str, Any]]]:
    out: Dict[str, Dict[str, Dict[str, Any]]] = {a: {} for a in arms}
    p = Path(cache_dir) / "eval4_checkpoint_records.jsonl"
    if not p.exists():
        print(f"[WARN] ablation checkpoint not found: {p}")
        return out
    with open(p, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except Exception:
                continue
            s = d.get("system")
            if s in out and d.get("qid"):
                out[s][d["qid"]] = d
    return out


def load_slice_last_wins(path: Path) -> Dict[str, Dict[str, Any]]:
    out: Dict[str, Dict[str, Any]] = {}
    if not path.exists():
        return out
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except Exception:
                continue
            if d.get("qid"):
                out[d["qid"]] = d
    return out


