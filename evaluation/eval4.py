def _summary_for_arm(arm: str, baseline: Dict[str, Dict[str, Any]],
                     recs: Dict[str, Dict[str, Any]]) -> Tuple[Dict[str, Any], Optional[float], Optional[float]]:
    common = sorted(q for q in recs if q in baseline)
    ac_base = [_finite(baseline[q].get("AnswerCorrectness")) or 0.0 for q in common]
    ac_arm = [_finite(recs[q].get("AnswerCorrectness")) or 0.0 for q in common]
    diffs = [a - b for a, b in zip(ac_arm, ac_base)]
    n = len(common)

    fc_base = [t1(baseline[q].get("AnswerCorrectness")) for q in common]
    fc_arm = [t1(recs[q].get("AnswerCorrectness")) for q in common]
    b = sum(1 for x, y in zip(fc_base, fc_arm) if x > y)
    c = sum(1 for x, y in zip(fc_base, fc_arm) if y > x)

    ac_mean = mean_or_none(ac_arm)
    ac_base_mean = mean_or_none(ac_base)
    d_ac = (ac_mean - ac_base_mean) if (ac_mean is not None and ac_base_mean is not None) else None
    ci_lo, ci_hi = bootstrap_ci_paired(diffs) if n else (float("nan"), float("nan"))
    p_ac = wilcoxon_p(diffs) if n else None
    p_fc = mcnemar_exact_p(b, c) if n else None

    fa_arm = mean_or_none([r.get("Faithfulness") for r in recs.values()])
    fa_base = mean_or_none([baseline[q].get("Faithfulness") for q in common])
    num_arm = mean_or_none([r.get("num_recall") for r in recs.values()])
    num_base = mean_or_none([baseline[q].get("num_recall") for q in common])

    grounded_arm = mean_or_none([grounded_fc(r) for r in recs.values()])
    grounded_base = mean_or_none([grounded_fc(baseline[q]) for q in common])

    tost = None
    if n and not math.isnan(ci_lo) and not math.isnan(ci_hi):
        tost = "equivalent (CI inside +/-3pp)" if (ci_lo > -TOST_BOUND and ci_hi < TOST_BOUND) else "not equivalent (a detectable difference exists)"

    return ({
        "Ablation arm": arm,
        "Arm label": ARM_DEFS[arm]["label"],
        "Removed component": ARM_DEFS[arm]["removed"],
        "Paired items": n,
        "AC": round(ac_mean, 4) if ac_mean is not None else None,
        "Baseline AC": round(ac_base_mean, 4) if ac_base_mean is not None else None,
        "ΔAC": round(d_ac, 4) if d_ac is not None else None,
        "dAC CI low": round(ci_lo, 4) if not math.isnan(ci_lo) else None,
        "dAC CI high": round(ci_hi, 4) if not math.isnan(ci_hi) else None,
        "Wilcoxon_p(AC)": round(p_ac, 5) if p_ac is not None else None,
        "McNemar_p(FC)": round(p_fc, 5) if p_fc is not None else None,
        "Cliff_δ(AC)": round(cliffs_delta(ac_arm, ac_base) or 0.0, 4),
        "FullyCorrect(%)": round(sum(fc_arm) / n * 100, 2) if n else None,
        "Baseline FC (%)": round(sum(fc_base) / n * 100, 2) if n else None,
        "ΔFC(pp)": round((sum(fc_arm) - sum(fc_base)) / n * 100, 2) if n else None,
        "GradedCorrectness": round(mean_or_none([graded(r.get("AnswerCorrectness")) for r in recs.values()]) or 0.0, 4),
        "GroundedFC(%)": round((grounded_arm or 0.0) * 100, 2),
        "Baseline GroundedFC (%)": round((grounded_base or 0.0) * 100, 2),
        "Faithfulness": round(fa_arm, 4) if fa_arm is not None else None,
        "ΔFaithfulness": round(fa_arm - fa_base, 4) if (fa_arm is not None and fa_base is not None) else None,
        "ContextPrecision": round(mean_or_none([r.get("ContextPrecision") for r in recs.values()]) or 0.0, 4),
        "ContextRecall": round(mean_or_none([r.get("ContextRecall") for r in recs.values()]) or 0.0, 4),
        "Numeric recall": round(num_arm, 4) if num_arm is not None else None,
        "Baseline numeric recall": round(num_base, 4) if num_base is not None else None,
        "Citation rate (%)": round((mean_or_none([r.get("has_cite") for r in recs.values()]) or 0.0) * 100, 2),
        "Recall@7": round(mean_or_none([r.get("Recall@7") for r in recs.values()]) or 0.0, 4),
        "MRR@7": round(mean_or_none([r.get("MRR@7") for r in recs.values()]) or 0.0, 4),
        "nDCG@7": round(mean_or_none([r.get("nDCG@7") for r in recs.values()]) or 0.0, 4),
        "CandidateRecall@50": round(mean_or_none([r.get("CandidateRecall@50") for r in recs.values()]) or 0.0, 4),
        "Success rate (%)": round((mean_or_none([1.0 if r.get("is_success") else 0.0 for r in recs.values()]) or 0.0) * 100, 2),
        "Mean context chars": round(mean_or_none([r.get("prompt_context_chars") for r in recs.values()]) or 0.0, 0),
        "Rerank P50 (ms)": round(_pct([r.get("rerank_latency_ms") for r in recs.values()], 50) or 0.0, 1),
        "Rerank P95 (ms)": round(_pct([r.get("rerank_latency_ms") for r in recs.values()], 95) or 0.0, 1),
        "End-to-end P50 (ms)": round(_pct([r.get("latency_ms") for r in recs.values()], 50) or 0.0, 1),
        "End-to-end P95 (ms)": round(_pct([r.get("latency_ms") for r in recs.values()], 95) or 0.0, 1),
        "Equivalence verdict (+/-3pp)": tost,
    }, p_ac, p_fc)


def _stratified_table(arms: List[str], baseline: Dict[str, Dict[str, Any]],
                      arm_recs: Dict[str, Dict[str, Dict[str, Any]]], key: str, dim_name: str) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for a in arms:
        buckets: Dict[str, List[str]] = {}
        for q in arm_recs[a]:
            buckets.setdefault(arm_recs[a][q].get(key, "?"), []).append(q)
        for cat, qids in sorted(buckets.items()):
            common = [q for q in qids if q in baseline]
            ac_arm = mean_or_none([arm_recs[a][q].get("AnswerCorrectness") for q in qids])
            ac_base = mean_or_none([baseline[q].get("AnswerCorrectness") for q in common]) if common else None
            diffs = [(_finite(arm_recs[a][q].get("AnswerCorrectness")) or 0.0) - (_finite(baseline[q].get("AnswerCorrectness")) or 0.0)
                     for q in common]
            lo, hi = bootstrap_ci_paired(diffs, n_boot=2000) if diffs else (float("nan"), float("nan"))
            b = sum(1 for q in common if t1(baseline[q].get("AnswerCorrectness")) > t1(arm_recs[a][q].get("AnswerCorrectness")))
            c = sum(1 for q in common if t1(arm_recs[a][q].get("AnswerCorrectness")) > t1(baseline[q].get("AnswerCorrectness")))
            rows.append({
                "Ablation arm": a,
                "Stratification": dim_name,
                "Category": cat,
                "N": len(qids),
                "AC": round(ac_arm, 4) if ac_arm is not None else None,
                "Baseline AC": round(ac_base, 4) if ac_base is not None else None,
                "ΔAC": round((ac_arm - ac_base), 4) if (ac_arm is not None and ac_base is not None) else None,
                "dAC CI low": round(lo, 4) if not math.isnan(lo) else None,
                "dAC CI high": round(hi, 4) if not math.isnan(hi) else None,
                "FC(%)": round(sum(t1(arm_recs[a][q].get("AnswerCorrectness")) for q in qids) / len(qids) * 100, 2),
                "Regressed": b,
                "Repaired": c,
                "McNemar_p": round(mcnemar_exact_p(b, c), 5) if common else None,
                "Recall@7": round(mean_or_none([arm_recs[a][q].get("Recall@7") for q in qids]) or 0.0, 4),
            })
    return pd.DataFrame(rows)


def _mechanism_table(arms: List[str], baseline: Dict[str, Dict[str, Any]],
                     arm_recs: Dict[str, Dict[str, Dict[str, Any]]], cache_dir: str) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []

    # ---- A1 reranker: rescue rate, damage rate and rank shift, computed on the arm that keeps reranking ----
    # Rank analysis uses the rerank-enabled arm, whose retrieval conditions match the full system
    rerank_arm = next((a for a in arms if ARM_DEFS[a]["use_reranker"] and ARM_DEFS[a]["use_bilingual"]), None) \
        or next((a for a in arms if ARM_DEFS[a]["use_reranker"]), None)
    if rerank_arm:
        recs = arm_recs[rerank_arm]
        rescue = damage = 0
        rank_before, rank_after = [], []
        for r in recs.values():
            cr = r.get("CandidateFirstRank") or 0
            sr = r.get("StrictFirstRank") or 0
            if cr:
                rank_before.append(cr)
            if sr:
                rank_after.append(sr)
            if cr > TOP_K_RERANK and sr > 0:
                rescue += 1
            if 0 < cr <= TOP_K_RERANK and sr == 0:
                damage += 1
        rows.append({
            "Mechanism": "A1 reranker",
            "Scope": f"rerank-enabled arm [{rerank_arm}] candidate pool versus strict top-{TOP_K_RERANK}",
            "Indicator": "rerank rescues (gold retrieval rank > 7 but inside the top 7 after reranking)",
            "Value": rescue,
        })
        rows.append({
            "Mechanism": "A1 reranker", "Scope": f"[{rerank_arm}]", "Indicator": "rerank damages (gold retrieval rank <= 7 but outside the top 7 after reranking)",
            "Value": damage,
        })
        rows.append({
            "Mechanism": "A1 reranker", "Scope": f"[{rerank_arm}]", "Indicator": "median gold retrieval rank",
            "Value": round(statistics.median(rank_before), 1) if rank_before else None,
        })
        rows.append({
            "Mechanism": "A1 reranker", "Scope": f"[{rerank_arm}]", "Indicator": "median gold rank after reranking",
            "Value": round(statistics.median(rank_after), 1) if rank_after else None,
        })

    # ---- A2 bilingual expansion: candidate-pool overlap and the English-chunk share ----
    bi_on = next((a for a in arms if ARM_DEFS[a]["use_bilingual"]), None)
    bi_off = next((a for a in arms if not ARM_DEFS[a]["use_bilingual"]), None)
    if bi_on and bi_off:
        pool_on = load_slice_last_wins(get_candidates_path(cache_dir, bi_on))
        pool_off = load_slice_last_wins(get_candidates_path(cache_dir, bi_off))
        strict_on = load_slice_last_wins(get_strict_contexts_path(cache_dir, bi_on))
        strict_off = load_slice_last_wins(get_strict_contexts_path(cache_dir, bi_off))
        jac, ov, same_top7 = [], [], 0
        for q in sorted(set(pool_on) & set(pool_off)):
            a = {str(c.get("block_id")) for c in (pool_on[q].get("candidates") or [])}
            b = {str(c.get("block_id")) for c in (pool_off[q].get("candidates") or [])}
            if a or b:
                jac.append(len(a & b) / max(1, len(a | b)))
                ov.append(len(a & b))
        for q in sorted(set(strict_on) & set(strict_off)):
            a = {str(c.get("block_id")) for c in (strict_on[q].get("strict_top5") or [])}
            b = {str(c.get("block_id")) for c in (strict_off[q].get("strict_top5") or [])}
            if a and a == b:
                same_top7 += 1
        rows.append({"Mechanism": "A2 bilingual expansion", "Scope": f"[{bi_on}] vs [{bi_off}]", "Indicator": "mean top-50 Jaccard",
                     "Value": round(statistics.mean(jac), 4) if jac else None})
        rows.append({"Mechanism": "A2 bilingual expansion", "Scope": f"[{bi_on}] vs [{bi_off}]", "Indicator": "mean top-50 overlapping chunks",
                     "Value": round(statistics.mean(ov), 2) if ov else None})
        rows.append({"Mechanism": "A2 bilingual expansion", "Scope": f"[{bi_on}] vs [{bi_off}]", "Indicator": f"items with an identical top-{TOP_K_RERANK}",
                     "Value": same_top7})
        for a in arms:
            rows.append({"Mechanism": "A2 bilingual expansion", "Scope": f"[{a}]", "Indicator": "mean English-dominant chunks in the top 7",
                         "Value": round(mean_or_none([r.get("english_blocks") for r in arm_recs[a].values()]) or 0.0, 3)})

    # ---- A3 context expansion and merging: trigger rate and structural labels ----
    for a in arms:
        recs = arm_recs[a]
        rows.append({"Mechanism": "A3 context expansion", "Scope": f"[{a}]", "Indicator": "items where enhancement would merge (% of items)",
                     "Value": round((mean_or_none([r.get("would_merge") for r in recs.values()]) or 0.0) * 100, 2)})
        rows.append({"Mechanism": "A3 context expansion", "Scope": f"[{a}]", "Indicator": "mean chunk count after enhancement",
                     "Value": round(mean_or_none([r.get("n_after_enhance") for r in recs.values()]) or 0.0, 3)})
        rows.append({"Mechanism": "A3 context expansion", "Scope": f"[{a}]", "Indicator": "mean character delta from enhancement",
                     "Value": round(mean_or_none([r.get("enhance_char_delta") for r in recs.values()]) or 0.0, 1)})
        rows.append({"Mechanism": "A3 context expansion", "Scope": f"[{a}]", "Indicator": "mean prompt context characters",
                     "Value": round(mean_or_none([r.get("prompt_context_chars") for r in recs.values()]) or 0.0, 0)})

    # ---- A4 metadata: citation behaviour (interpretability and traceability) ----
    for a in arms:
        recs = arm_recs[a]
        rows.append({"Mechanism": "A4 metadata injection", "Scope": f"[{a}]", "Indicator": "answers citing [evidence N] (%)",
                     "Value": round((mean_or_none([r.get("has_cite") for r in recs.values()]) or 0.0) * 100, 2)})
        rows.append({"Mechanism": "A4 metadata injection", "Scope": f"[{a}]", "Indicator": "answers naming the source (%)",
                     "Value": round((mean_or_none([r.get("source_mention") for r in recs.values()]) or 0.0) * 100, 2)})
        rows.append({"Mechanism": "A4 metadata injection", "Scope": f"[{a}]", "Indicator": "answers naming the section (%)",
                     "Value": round((mean_or_none([r.get("section_mention") for r in recs.values()]) or 0.0) * 100, 2)})
        rows.append({"Mechanism": "A4 metadata injection", "Scope": f"[{a}]", "Indicator": "citations per 1000 characters",
                     "Value": round(mean_or_none([(r.get("cite_count") or 0) / max(1, len(r.get("generated_answer") or "")) * 1000
                                                 for r in recs.values()]) or 0.0, 3)})
    return rows


def _subset_table(arms: List[str], baseline: Dict[str, Dict[str, Any]],
                  arm_recs: Dict[str, Dict[str, Dict[str, Any]]], cache_dir: str) -> List[Dict[str, Any]]:
    """Key subset contrast: on which question types the ablation actually matters."""
    rows: List[Dict[str, Any]] = []

    def add(arm: str, subset: str, qids: List[str], note: str = "") -> None:
        qids = [q for q in qids if q in arm_recs[arm]]
        if not qids:
            return
        common = [q for q in qids if q in baseline]
        ac = mean_or_none([arm_recs[arm][q].get("AnswerCorrectness") for q in qids])
        base = mean_or_none([baseline[q].get("AnswerCorrectness") for q in common]) if common else None
        diffs = [(_finite(arm_recs[arm][q].get("AnswerCorrectness")) or 0.0) - (_finite(baseline[q].get("AnswerCorrectness")) or 0.0)
                 for q in common]
        lo, hi = bootstrap_ci_paired(diffs, n_boot=2000) if diffs else (float("nan"), float("nan"))
        rows.append({
            "Ablation arm": arm,
            "Subset": subset,
            "N": len(qids),
            "AC": round(ac, 4) if ac is not None else None,
            "Baseline AC": round(base, 4) if base is not None else None,
            "ΔAC": round((ac - base), 4) if (ac is not None and base is not None) else None,
            "dAC CI low": round(lo, 4) if not math.isnan(lo) else None,
            "dAC CI high": round(hi, 4) if not math.isnan(hi) else None,
            "Note": note,
        })

    for a in arms:
        recs = arm_recs[a]
        qids = list(recs.keys())
        add(a, "All", qids)
        add(a, "numeric (reference contains a number)", [q for q in qids if (recs[q].get("num_ref") or 0) > 0])
        add(a, "table (top 7 contains a table chunk)", [q for q in qids if recs[q].get("has_table") == 1])
        add(a, "formula (top 7 contains a formula chunk)", [q for q in qids if recs[q].get("has_formula") == 1])
        add(a, "multi-source (top 7 spans >= 2 documents)", [q for q in qids if (recs[q].get("n_sources") or 0) >= 2])
        add(a, "contains English evidence", [q for q in qids if (recs[q].get("english_blocks") or 0) > 0])
        for t in ("comparison", "extraction", "multi-hop", "reasoning", "summarization"):
            add(a, f"task type: {t}", [q for q in qids if recs[q].get("task_type") == t])
        if not ARM_DEFS[a]["use_ctx_enhance"]:
            add(a, "A3 control: enhancement would merge", [q for q in qids if recs[q].get("would_merge") == 1], "natural control group: items where the module should take effect")
            add(a, "A3 control: enhancement would not merge", [q for q in qids if recs[q].get("would_merge") == 0], "natural control group: items where the module has no effect")
    return rows


def _conclusion_draft(arms: List[str], baseline: Dict[str, Dict[str, Any]],
                      arm_recs: Dict[str, Dict[str, Dict[str, Any]]],
                      df_sum: pd.DataFrame, df_trans: pd.DataFrame,
                      df_mech: pd.DataFrame, df_subset: pd.DataFrame) -> str:
    lines: List[str] = []
    lines.append("# Ablation summary\n")
    lines.append(f"- Baseline: `{BASELINE_NAME}` (final Experiment 3 RAGAS results, read-only reuse; no intermediate cache reused)")
    lines.append(f"- Ablation arms: {len(arms)}, each removing a single component, everything else held constant")
    lines.append("- Primary metrics: AnswerCorrectness (RAGAS, GLM-5.3-Flash as an independent judge) and Fully Correct Rate (AC >= 0.75)\n")

    lines.append("## 1. Overall results (paired against the baseline)\n")
    lines.append("| Ablation arm | Removed component | dAC | 95% CI | McNemar p (FC) | Holm p (AC) | dFC (pp) | Equivalence (+/-3pp) |")
    lines.append("|---|---|---:|---|---:|---:|---:|---|")
    for _, r in df_sum.iterrows():
        lines.append(
            f"| {r['Ablation arm']} | {r['Removed component']} | {r['dAC']} | "
            f"[{r['dAC CI low']}, {r['dAC CI high']}] | {r['McNemar p (FC)']} | {r['Holm-adjusted p (AC)']} | "
            f"{r['dFC (pp)']} | {r['Equivalence verdict (+/-3pp)']} |"
        )

    lines.append("\n## 2. Repair and regression rates\n")
    lines.append("| Ablation arm | Regressed | Repaired | Regression rate (%) | Repair rate (%) | Net change (pp) |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    for _, r in df_trans.iterrows():
        lines.append(f"| {r['Ablation arm']} | {r['Regressed']} | {r['Repaired']} | "
                     f"{r['Regression rate (%)']} | {r['Repair rate (%)']} | {r['Net change (pp)']} |")

    lines.append("\n## 3. Mechanism indicators (the 'why')\n")
    lines.append("| Mechanism | Scope | Indicator | Value |")
    lines.append("|---|---|---|---:|")
    for _, r in df_mech.iterrows():
        lines.append(f"| {r['Mechanism']} | {r['Scope']} | {r['Indicator']} | {r['Value']} |")

    lines.append("\n## 4. Key subsets (the 'where')\n")
    lines.append("| Ablation arm | Subset | N | dAC | 95% CI |")
    lines.append("|---|---|---:|---:|---|")
    for _, r in df_subset.iterrows():
        if r["Subset"] == "All":
            continue
        lines.append(f"| {r['Ablation arm']} | {r['Subset']} | {r['N']} | {r['dAC']} | "
                     f"[{r['dAC CI low']}, {r['dAC CI high']}] |")

    lines.append("\n## 5. Wording to confirm by hand\n")
    lines.append("- When an arm's 95% CI for dAC spans 0 and the equivalence verdict is 'equivalent', state that the component "
                 "makes no material contribution to answer correctness but has independent value for interpretability, traceability or latency. Never write that it 'has no effect'.")
    lines.append("- For the metadata arm, cite the interpretability and traceability indicators (citation rate, source and section mention rate) rather than the accuracy.")
    lines.append("- Cross-check every number against `eval4_summary_table.csv`, `eval4_stratified_task.csv` and `eval4_subset_contrast.csv`.")
    return "\n".join(lines) + "\n"

