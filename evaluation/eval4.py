def build_context_with_metadata(records: List[Dict]) -> str:
    """Full variant: call general_RAG.build_rag_context verbatim (U-shape ordering and character budget included)."""
    return build_rag_context(records)


def build_context_no_metadata(records: List[Dict]) -> str:
    """
    A4 variant: keep the [evidence N] numbering, the U-shape ordering, the per-chunk and total
    character budgets and the evidence order, and strip only the identifying metadata:
        . the source/section/(contains table) labels injected by build_rag_context
        . the [paragraph] and [table] labels and the markdown code fence injected by enhance_context
    """
    from rag_core.general_RAG import reorder_to_u_shape

    if records:
        records = reorder_to_u_shape(records)

    context_parts: List[str] = []
    used = 0
    for rank, record in enumerate(records, 1):
        raw = str(record.get("text", "")).strip()
        if not raw:
            continue
        # (1) Truncate and budget exactly as Full does (Full truncates the labelled text), so the
        #     body window of A4 matches Full verbatim and the only difference is the stripped labels.
        text = raw[:GEN_CONTEXT_MAX_CHARS_PER_DOC]
        if used + len(text) > GEN_CONTEXT_MAX_CHARS_TOTAL:
            remaining = GEN_CONTEXT_MAX_CHARS_TOTAL - used
            if remaining <= 0:
                break
            text = text[:remaining]
        used += len(text)
        # (2) Strip the identifying metadata (A3 differs only in that it keeps the merged result)
        text = TAG_PARA_RE.sub("", text)
        text = TAG_TABLE_RE.sub("", text)
        text = MD_FENCE_RE.sub(r"\1", text)
        text = re.sub(r"\n{3,}", "\n\n", text).strip()
        context_parts.append(f"[证据{rank}]\n{text}")
        if used >= GEN_CONTEXT_MAX_CHARS_TOTAL:
            break
    return "\n\n".join(context_parts)


def build_prompt_context(records: List[Dict], use_metadata: bool, backfill_table_flag: bool = False) -> str:
    """
    Single entry point for context construction:
      use_metadata=True  -> production build_rag_context (verbatim);
      use_metadata=False -> build_context_no_metadata (identifying metadata stripped only).

    backfill_table_flag is True only for A3 (use_ctx_enhance=False): once enhance_context is
    removed the _has_table flag it used to write is missing, so it is restored from block_type
    here; otherwise the metadata layer would lose its (contains table) label along with the
    module. Full always passes False and therefore matches production output verbatim.
    """
    if not use_metadata:
        return build_context_no_metadata(records)
    if backfill_table_flag:
        records = [
            (r if r.get("_has_table") is not None else dict(r, _has_table=(r.get("block_type") == "table")))
            for r in records
        ]
    return build_rag_context(records)


