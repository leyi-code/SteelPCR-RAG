def get_checkpoint_path(cache_dir: str = EVAL4_CACHE_DIR) -> Path:
    p = Path(cache_dir)
    p.mkdir(parents=True, exist_ok=True)
    return p / "eval4_checkpoint_records.jsonl"


def load_all_checkpoint_records(cache_dir: str = EVAL4_CACHE_DIR) -> Dict[str, Dict[str, Any]]:
    records: Dict[str, Dict[str, Any]] = {}
    path = get_checkpoint_path(cache_dir)
    if not path.exists():
        return records
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                d = json.loads(line)
            except Exception:
                continue
            records[f"{d.get('system')}_{d.get('qid')}"] = d
    return records


def build_skip_cache(all_records: Dict[str, Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """Only records passing both validation layers enter the instant skip set."""
    skip: Dict[str, Dict[str, Any]] = {}
    for key, d in all_records.items():
        ok, _ = validate_record_integrity(d)
        if ok and d.get("context_sha1"):
            skip[key] = d
    return skip


def update_or_append_checkpoint_record(cache_dir: str, record: Dict[str, Any]) -> None:
    """Atomic row replacement: a stale (system, qid) row is overwritten in place, so no duplicates accumulate."""
    path = get_checkpoint_path(cache_dir)
    if not path.exists():
        _append_jsonl(path, record)
        return
    tmp = path.with_suffix(".tmp")
    target = f"{record.get('system')}_{record.get('qid')}"
    replaced = False
    with open(path, "r", encoding="utf-8") as f_in, open(tmp, "w", encoding="utf-8") as f_out:
        for line in f_in:
            s = line.strip()
            if not s:
                continue
            try:
                d = json.loads(s)
            except Exception:
                continue
            if f"{d.get('system')}_{d.get('qid')}" == target:
                f_out.write(json.dumps(record, ensure_ascii=False) + "\n")
                replaced = True
            else:
                f_out.write(s + "\n")
        if not replaced:
            f_out.write(json.dumps(record, ensure_ascii=False) + "\n")
        f_out.flush()
    os.replace(tmp, path)


def backup_checkpoint(cache_dir: str) -> Optional[Path]:
    path = get_checkpoint_path(cache_dir)
    if not path.exists() or path.stat().st_size == 0:
        return None
    bak = path.with_name(path.name + f".bak_{time.strftime('%Y%m%d_%H%M%S')}")
    with open(path, "rb") as f_in, open(bak, "wb") as f_out:
        f_out.write(f_in.read())
    return bak


def repair_nan_checkpoint_records(cache_dir: str = EVAL4_CACHE_DIR) -> int:
    """Single-metric NaN repair: only NaN metrics are re-scored, an unrepairable one keeps its NaN (and stays non-skippable)."""
    path = get_checkpoint_path(cache_dir)
    if not path.exists():
        return 0
    tmp = path.with_suffix(".tmp")
    fixed = 0
    with open(path, "r", encoding="utf-8") as f_in, open(tmp, "w", encoding="utf-8") as f_out:
        for line in f_in:
            s = line.strip()
            if not s:
                continue
            d = json.loads(s)
            ans_ok = (
                bool(d.get("is_success"))
                and bool(d.get("generated_answer"))
                and not str(d.get("generated_answer")).startswith("ERROR:")
                and d.get("finish_reason") != "length"
            )
            if ans_ok:
                for k in ("AnswerCorrectness", "Faithfulness", "ContextPrecision", "ContextRecall"):
                    v = d.get(k)
                    if v is None or (isinstance(v, float) and math.isnan(v)):
                        if k != "AnswerCorrectness" and not d.get("contexts"):
                            continue
                        print(f"   [REPAIR] [{d.get('system')}_{d.get('qid')}] metric [{k}] is NaN; re-running it ...")
                        sample = dict(d)
                        sample["is_closed_book"] = False
                        new_v = evaluate_single_specific_metric(
                            sample,
                            metric_name=k,
                            llm_binding_host=EVAL_LLM_API_BASE,
                            llm_api_key=EVAL_LLM_API_KEY,
                            llm_model=EVAL_LLM_MODEL,
                            embed_binding_host=EVAL_EMBED_API_BASE,
                            embed_api_key=EVAL_EMBED_API_KEY,
                            embed_model=EVAL_EMBED_MODEL,
                        )
                        if new_v is not None:
                            d[k] = new_v
                            fixed += 1
                            print(f"      [OK] [{k}] repaired: {new_v}")
                        else:
                            print(f"      [WARN] [{k}] repair failed, NaN kept (this item stays non-skippable)")
            f_out.write(json.dumps(d, ensure_ascii=False) + "\n")
            f_out.flush()
    os.replace(tmp, path)
    if fixed:
        print(f"[OK] In-place NaN repair finished: {fixed} metric value(s) repaired.")
    return fixed


def _is_missing(v: Any) -> bool:
    return v is None or (isinstance(v, float) and math.isnan(v))


def evaluate_ragas_robust(
    record: Dict[str, Any],
    retry: int = RAGAS_RETRY,
    backoff: float = RAGAS_BACKOFF,
) -> Dict[str, float]:
    """
    Four RAGAS metrics, automatic retry on NaN, single-metric repair as the last resort.

    In practice the judge endpoint (GLM-5.3-Flash) is rate-limited and AnswerCorrectness
    occasionally comes back NaN. The strategy (never silently writing 0.0) is:
      1) run all four metrics once;
      2) if any is NaN, back off exponentially and re-run the block, filling in only the missing ones;
      3) if a metric is still missing, re-score just that one with eval3.evaluate_single_specific_metric;
      4) a record still holding NaN fails the two-layer validation, stays non-skippable and is retried on the next run.
    """
    metrics = evaluate_single_ragas_sample(
        record,
        llm_binding_host=EVAL_LLM_API_BASE,
        llm_api_key=EVAL_LLM_API_KEY,
        llm_model=EVAL_LLM_MODEL,
        embed_binding_host=EVAL_EMBED_API_BASE,
        embed_api_key=EVAL_EMBED_API_KEY,
        embed_model=EVAL_EMBED_MODEL,
        max_retries=EVAL_MAX_RETRIES,
    )
    for attempt in range(1, max(0, retry) + 1):
        missing = [k for k in RAGAS_KEYS if _is_missing(metrics.get(k))]
        if not missing:
            break
        wait = backoff * (2 ** (attempt - 1))
        print(f"      [RETRY] RAGAS still missing {missing}; backing off {wait:.0f}s and re-running the block ({attempt}/{retry}) ...")
        time.sleep(wait)
        again = evaluate_single_ragas_sample(
            record,
            llm_binding_host=EVAL_LLM_API_BASE,
            llm_api_key=EVAL_LLM_API_KEY,
            llm_model=EVAL_LLM_MODEL,
            embed_binding_host=EVAL_EMBED_API_BASE,
            embed_api_key=EVAL_EMBED_API_KEY,
            embed_model=EVAL_EMBED_MODEL,
            max_retries=EVAL_MAX_RETRIES,
        )
        for k in RAGAS_KEYS:
            if _is_missing(metrics.get(k)) and not _is_missing(again.get(k)):
                metrics[k] = again[k]

    for k in [k for k in RAGAS_KEYS if _is_missing(metrics.get(k))]:
        print(f"      [REPAIR] metric [{k}] still missing; re-scoring it on its own ...")
        v = evaluate_single_specific_metric(
            record,
            metric_name=k,
            llm_binding_host=EVAL_LLM_API_BASE,
            llm_api_key=EVAL_LLM_API_KEY,
            llm_model=EVAL_LLM_MODEL,
            embed_binding_host=EVAL_EMBED_API_BASE,
            embed_api_key=EVAL_EMBED_API_KEY,
            embed_model=EVAL_EMBED_MODEL,
        )
        if v is not None:
            metrics[k] = v
            print(f"      [OK] metric [{k}] repaired: {v}")
    return metrics


def decide_rerun_level(
    raw_record: Optional[Dict[str, Any]],
    arm_def: Dict[str, Any],
    saved_candidates: Optional[List[Dict]],
    saved_strict: Optional[List[Dict]],
    saved_prompt: Optional[Dict],
) -> str:
    """
    Graded re-run diagnosis:
      LEVEL_3_FULL_PIPELINE  : no record, evidence and candidate pool both missing -> full chain
      LEVEL_2B_RERANK_ONLY   : candidate pool intact but evidence damaged -> rebuild evidence from the pool (including the rerank)
      LEVEL_2A_GENERATE_ONLY : evidence and prompt context intact, only generation or scoring lost -> redo generation plus RAGAS
    """
    if not raw_record:
        return "LEVEL_3_FULL_PIPELINE"

    err = str(raw_record.get("error_msg") or "")
    ans = str(raw_record.get("generated_answer") or "").strip()
    is_succ = raw_record.get("is_success")

    gen_damaged = (
        (not is_succ)
        or ("empty content" in err)
        or ("502" in err)
        or (not ans)
        or ans.startswith("ERROR:")
        or (not any(ans.endswith(c) for c in NORMAL_ENDINGS))
        or raw_record.get("finish_reason") == "length"
    )

    if "rerank" in err.lower():
        if saved_candidates and len(saved_candidates) >= TOP_K_RERANK:
            return "LEVEL_2B_RERANK_ONLY"
        return "LEVEL_3_FULL_PIPELINE"

    if gen_damaged:
        if saved_strict and saved_prompt and saved_prompt.get("prompt_context"):
            return "LEVEL_2A_GENERATE_ONLY"
        if saved_candidates and len(saved_candidates) >= TOP_K_RERANK:
            return "LEVEL_2B_RERANK_ONLY"
        return "LEVEL_3_FULL_PIPELINE"

    return "LEVEL_3_FULL_PIPELINE"


