    print(f"[OK] summary table saved: {out_dir / 'eval4_summary_table.csv'}")
    print("\n" + "=" * 100)
    print("\U0001f4ca Ablation core result matrix")
    print("=" * 100)
    with pd.option_context("display.width", 240, "display.max_columns", 60):
        print(df_sum.to_string(index=False))
    print("=" * 100)

    # ---------- 3.3 Paired transition matrix ----------
    trans_rows: List[Dict[str, Any]] = []
    for a in arms:
        common = [q for q in arm_recs[a] if q in baseline]
        b = c = both_ok = both_bad = 0
        for q in common:
            base_ok = t1(baseline[q].get("AnswerCorrectness")) > 0
            arm_ok = t1(arm_recs[a][q].get("AnswerCorrectness")) > 0
            if base_ok and not arm_ok:
                b += 1
            elif (not base_ok) and arm_ok:
                c += 1
            elif base_ok and arm_ok:
                both_ok += 1
            else:
                both_bad += 1
        n = len(common)
        trans_rows.append({
            "Ablation arm": a,
            "Paired items": n,
            "Baseline right / arm wrong (regressed)": b,
            "Baseline wrong / arm right (repaired)": c,
            "Both right": both_ok,
            "Both wrong": both_bad,
            "Regression rate (%)": round(b / n * 100, 2) if n else None,
            "Repair rate (%)": round(c / n * 100, 2) if n else None,
            "Net change (pp)": round((c - b) / n * 100, 2) if n else None,
            "McNemar_p(FC)": round(mcnemar_exact_p(b, c), 5),
        })
    df_trans = pd.DataFrame(trans_rows)
    df_trans.to_csv(out_dir / "eval4_paired_transitions.csv", index=False, encoding="utf-8-sig")
    print(f"[OK] paired transition matrix saved: {out_dir / 'eval4_paired_transitions.csv'}")

    # ---------- 3.4 Stratified tables ----------
    strat_task = _stratified_table(arms, baseline, arm_recs, "task_type", "Task Type")
    strat_topic = _stratified_table(arms, baseline, arm_recs, "topic", "Domain Topic")
    strat_task.to_csv(out_dir / "eval4_stratified_task.csv", index=False, encoding="utf-8-sig")
    strat_topic.to_csv(out_dir / "eval4_stratified_topic.csv", index=False, encoding="utf-8-sig")
    print(f"[OK] stratified tables saved: eval4_stratified_task.csv / eval4_stratified_topic.csv")

    # ---------- 3.5 Mechanism indicators ----------
    mech_rows = _mechanism_table(arms, baseline, arm_recs, cache_dir)
    df_mech = pd.DataFrame(mech_rows)
    df_mech.to_csv(out_dir / "eval4_mechanism_metrics.csv", index=False, encoding="utf-8-sig")
    print(f"[OK] mechanism indicator table saved: {out_dir / 'eval4_mechanism_metrics.csv'}")

    # ---------- 3.6 Subset contrast (the key stratification of the ablation) ----------
    subset_rows = _subset_table(arms, baseline, arm_recs, cache_dir)
    df_subset = pd.DataFrame(subset_rows)
    df_subset.to_csv(out_dir / "eval4_subset_contrast.csv", index=False, encoding="utf-8-sig")
    print(f"[OK] subset contrast table saved: {out_dir / 'eval4_subset_contrast.csv'}")

    # ---------- 3.7 Figure data ----------
    fig_data = {
        "baseline": BASELINE_NAME,
        "arms": {a: ARM_DEFS[a]["label"] for a in arms},
        "ac_mean": {a: mean_or_none([r.get("AnswerCorrectness") for r in arm_recs[a].values()]) for a in arms},
        "fc_rate": {a: mean_or_none([t1(r.get("AnswerCorrectness")) for r in arm_recs[a].values()]) for a in arms},
        "retrieval": {
            a: {
                "Recall@7": mean_or_none([r.get("Recall@7") for r in arm_recs[a].values()]),
                "MRR@7": mean_or_none([r.get("MRR@7") for r in arm_recs[a].values()]),
                "nDCG@7": mean_or_none([r.get("nDCG@7") for r in arm_recs[a].values()]),
            } for a in arms
        },
        "latency_p50_p95": {
            a: {
                "rerank_p50": _pct([r.get("rerank_latency_ms") for r in arm_recs[a].values()], 50),
                "rerank_p95": _pct([r.get("rerank_latency_ms") for r in arm_recs[a].values()], 95),
                "e2e_p50": _pct([r.get("latency_ms") for r in arm_recs[a].values()], 50),
                "e2e_p95": _pct([r.get("latency_ms") for r in arm_recs[a].values()], 95),
            } for a in arms
        },
        "task_type_dist": {a: _task_dist(arm_recs[a]) for a in arms},
    }
    with open(out_dir / "eval4_figure_data.json", "w", encoding="utf-8") as f:
        json.dump(fig_data, f, ensure_ascii=False, indent=1)
    print(f"[OK] figure data saved: {out_dir / 'eval4_figure_data.json'}")

    # ---------- 3.8 Summary conclusions ----------
    summary = _conclusion_draft(arms, baseline, arm_recs, df_sum, df_trans, df_mech, df_subset)
    (out_dir / "ablation_summary.md").write_text(summary, encoding="utf-8")
    print(f"[OK] summary conclusions saved: {out_dir / 'ablation_summary.md'}")


