NORMAL_ENDINGS = ("。", "！", "？", ".", "!", "?", "”", "’", "）", ")", "]", "】", "%")
NUM_RE = re.compile(r"(?<![0-9.])([0-9]+(?:[.,][0-9]+)?)(?![0-9])")
CJK_RE = re.compile(r"[\u4e00-\u9fff]")
LATIN_RE = re.compile(r"[A-Za-z]")
CITE_RE = re.compile(r"(?:\[\u8bc1\u636e\s*(\d+)\]|\u8bc1\u636e\s*(\d+))", re.IGNORECASE)

TAG_PARA_RE = re.compile(r"^[ \t]*\[段落：.*?\][ \t]*$", re.M)
TAG_TABLE_RE = re.compile(r"^[ \t]*【表格：.*?】[ \t]*$", re.M)
MD_FENCE_RE = re.compile(r"```markdown\n(.*?)\n```", re.S)


def _norm_text(t: str) -> str:
    return re.sub(r"[\s\W_]+", "", (t or "").lower())


def safe_name(name: str) -> str:
    return name.lower().replace("-", "_").replace("/", "_").replace(" ", "_")


def numbers_of(text: str) -> List[str]:
    """Extract checkable numbers (same convention as the numeric analysis: no thousands separators, at least two significant digits)."""
    out = []
    for n in NUM_RE.findall(text or ""):
        v = n.replace(",", "").rstrip(".")
        if len(v.replace(".", "")) >= 2:
            out.append(v)
    return out


def numeric_accuracy(reference: str, generated: str) -> Dict[str, Any]:
    """Numeric accuracy, a deterministic zero-cost metric: recall over the reference numbers, precision over the generated ones."""
    a, b = numbers_of(reference), numbers_of(generated)
    if not a:
        return {"num_ref": 0, "num_gen": len(b), "num_recall": None, "num_precision": None}
    sa, sb = set(a), set(b)
    inter = len(sa & sb)
    return {
        "num_ref": len(sa),
        "num_gen": len(sb),
        "num_recall": inter / len(sa),
        "num_precision": (inter / len(sb)) if sb else 0.0,
    }


def citation_stats(answer: str, docs: Sequence[Dict]) -> Dict[str, Any]:
    """Interpretability and traceability indicators, the main observation targets of the metadata ablation."""
    ans = answer or ""
    cites = [m.group(1) or m.group(2) for m in CITE_RE.finditer(ans)]
    norm_ans = _norm_text(ans)
    src_hit = 0
    sec_hit = 0
    for d in docs or []:
        src = (d.get("doc_title") or d.get("source_file") or "").strip()
        sec = (d.get("head_section") or "").strip()
        if len(src) >= 8 and _norm_text(src)[:12] and _norm_text(src)[:12] in norm_ans:
            src_hit += 1
        if len(sec) >= 4 and _norm_text(sec)[:8] and _norm_text(sec)[:8] in norm_ans:
            sec_hit += 1
    return {
        "cite_count": len(cites),
        "unique_cite": len(set(cites)),
        "has_cite": 1 if cites else 0,
        "source_mention": 1 if src_hit else 0,
        "section_mention": 1 if sec_hit else 0,
        "mentions_evidence_word": 1 if "证据" in ans else 0,
    }


def english_stats(docs: Sequence[Dict]) -> Dict[str, Any]:
    """Mechanism indicator for bilingual expansion: how many of the top-7 chunks are predominantly English."""
    n = len(docs or [])
    en = 0
    for d in docs or []:
        t = d.get("text", "") or ""
        if len(LATIN_RE.findall(t)) > len(CJK_RE.findall(t)):
            en += 1
    return {"english_blocks": en, "english_ratio": (en / n) if n else 0.0}


def source_stats(docs: Sequence[Dict]) -> Dict[str, Any]:
    """Evidence-source distribution, the stratification basis for the metadata ablation (multi-source items show its value)."""
    srcs = set()
    for d in docs or []:
        s = (d.get("source_file") or d.get("doc_title") or "").strip()
        if s:
            srcs.add(s)
    return {"n_sources": len(srcs)}


