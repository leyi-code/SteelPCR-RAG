# 8. Dataset sampling (deterministic; used for smoke and pilot runs)
# ==============================================================================
def stratified_subset(dataset: List[Dict[str, Any]], total: int) -> List[Dict[str, Any]]:
    """Allocate proportionally across question types and sample evenly within each type, so all five types stay covered and the sample is reproducible."""
    if total <= 0:
        return []
    if total >= len(dataset):
        return list(dataset)
    by_type: Dict[str, List[Dict[str, Any]]] = {}
    for r in dataset:
        by_type.setdefault(r["task_type"], []).append(r)
    picked: List[Dict[str, Any]] = []
    for t, rows in sorted(by_type.items()):
        quota = max(1, round(total * len(rows) / len(dataset)))
        quota = min(quota, len(rows))
        step = len(rows) / quota
        idxs = sorted({min(len(rows) - 1, int(round(i * step))) for i in range(quota)})
        picked.extend(rows[i] for i in idxs)
    picked.sort(key=lambda r: r["qid"])
    return picked


